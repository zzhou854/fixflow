def report(
    *,
    run_int: int = 1,
    metrics: EvaluationMetrics | None = None,
    dataset_id: str = "resident_interpretation",
    dataset_version: str = "1.0.0",
    dataset_hash: str = "a" * 64,
    policy_id: str = "resident_interpretation_gate",
    policy_version: str = "1.0.0",
    policy_hash: str = "b" * 64,
    provider: str = "fake",
    model: str = "model",
    live_network: bool = False,
    dirty: bool = False,
) -> EvaluationReport:
    now = datetime(2026, 7, 23, tzinfo=UTC)
    manifest = EvaluationRunManifest(
        run_id=UUID(int=run_int),
        run_schema_version="evaluation-run-v1",
        run_status=EvaluationRunStatus.COMPLETED,
        dataset_id=dataset_id,
        dataset_version=dataset_version,
        dataset_hash=dataset_hash,
        policy_id=policy_id,
        policy_version=policy_version,
        policy_hash=policy_hash,
        scorer_id="resident_interpretation_scorer",
        scorer_version="1.0.0",
        provider_configuration=provider_configuration(
            provider=provider,
            model=model,
            live_network=live_network,
        ),
        concurrency=1,
        repeat_count=1,
        code_commit="1" * 40,
        git_dirty=dirty,
        settings_fingerprint="c" * 64,
        created_at_utc=now,
        completed_at_utc=now,
        case_count=10,
    )
    return EvaluationReport(
        report_schema_version="evaluation-report-v1",
        manifest=manifest,
        metrics=metrics or passing_metrics(),
    )
